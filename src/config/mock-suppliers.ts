export function findSupplierById(
  id: string,
  catalog: readonly SupplierRecord[] = INITIAL_SUPPLIERS,
): SupplierRecord | undefined {
  return catalog.find((s) => s.id === id);
}

export function computeSupplierSummary(suppliers: readonly SupplierRecord[]) {
  let active = 0;
  let inactive = 0;
  let totalPurchases = 0;
  let totalPayments = 0;
  let outstanding = 0;

  for (const s of suppliers) {
    if (s.status === "active") active += 1;
    else inactive += 1;
    totalPurchases += s.totalPurchases;
    totalPayments += s.totalPayments;
    outstanding += s.balance;
  }

  return {
    total: suppliers.length,
    active,
    inactive,
    totalPurchases,
    totalPayments,
    outstanding,
    currency: SUPPLIER_REPORTING_CURRENCY,
  };
}
