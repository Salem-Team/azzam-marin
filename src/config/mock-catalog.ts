export function findItemById(id: string): CatalogItem | undefined {
  return CATALOG_ITEMS.find((item) => item.id === id);
}

export function findItemByCode(itemCode: string): CatalogItem | undefined {
  return CATALOG_ITEMS.find(
    (item) => item.itemCode.toLowerCase() === itemCode.toLowerCase(),
  );
}

export function findSparePartById(id: string): SparePartRecord | undefined {
  return SPARE_PARTS.find((part) => part.id === id);
}

export function findSparePartByPartNumber(
  partNumber: string,
): SparePartRecord | undefined {
  return SPARE_PARTS.find(
    (part) => part.partNumber.toLowerCase() === partNumber.toLowerCase(),
  );
}

export function findEngineById(id: string): MarineEngineRecord | undefined {
  return MARINE_ENGINES.find((engine) => engine.id === id);
}

export function sparePartsForItem(itemId: string): SparePartRecord[] {
  return SPARE_PARTS.filter((part) => part.itemId === itemId);
}

export function enginesForSparePart(partId: string): MarineEngineRecord[] {
  const part = findSparePartById(partId);
  if (!part) return [];
  return part.compatibleEngineIds
    .map((id) => findEngineById(id))
    .filter((e): e is MarineEngineRecord => e != null);
}

/**
 * @deprecated Prefer `sparePartsCompatibleWithEngine` from spare-parts-store
 * (live specialized records). Seed reverse IDs are not updated by spare CRUD.
 */
export function sparePartsForEngine(engineId: string): SparePartRecord[] {
  const engine = findEngineById(engineId);
  if (!engine) return [];
  return engine.compatibleSparePartIds
    .map((id) => findSparePartById(id))
    .filter((p): p is SparePartRecord => p != null);
}
